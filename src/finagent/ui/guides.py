def _guide(definition: str, interpretation: str, calculation: str = "") -> str:
    parts = [f"[정의] {definition.strip()}", f"[해석] {interpretation.strip()}"]
    if calculation.strip():
        parts.append(f"[산출] {calculation.strip()}")
    return "\n\n".join(parts).replace("\\~", "~").replace("~", "\\~")


def _each(prefixes: tuple[str, ...], name: str, text: str) -> dict[str, str]:
    return {f"{prefix}_{name}": text for prefix in prefixes}


